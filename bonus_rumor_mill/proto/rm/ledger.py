"""The Facts Ledger from Class 10, split in two: one truth ledger of what really
happened, and a belief ledger for each character. Saved to disk after every update.

Everything in it is generated by the night shift. Nothing here is hand-written."""
from __future__ import annotations

import copy
import json
import os
import re
import threading
import time
from pathlib import Path

from . import cast

STATE_DIR = Path(__file__).resolve().parent.parent / "state"


def fresh(premise_no: int, seed: int) -> dict:
    return {
        "meta": {"game": "Rumor Mill, Milestone 1", "day": cast.GAME_DAY, "premise": premise_no, "seed": seed,
                 "clock": cast.DAY_START, "heat": 0.0, "tier": cast.TIERS[0][1], "believers": 0,
                 "outcome": None, "twist": None},
        "town": {},
        "truth": {},
        "npcs": {
            key: {
                "personality": c["type"],
                "job": None, "building": None, "place": None,
                "relationships": {}, "secret": None,
                "talks_to": {},
                "timeline": {},
                "saw": [],
                "beliefs": {},
                "status": [],
                "said_to_player": [],
                "cracked": False,
                "corrected": False,
            }
            for key, c in cast.CAST.items()
        },
        "rumors": {},
        "mutation_log": [],
        "lies": {},
        "evidence": {},
        "quest": [],
        "solvability": [],
        "morning": {},
        "player": {"evidence": [], "visited": [], "said": [], "accusations": [], "shown": [], "actions": []},
        "night_log": [],
    }


class Ledger:
    def __init__(self, premise_no: int = 1, seed: int = 0, keep_log: bool = False):
        self.lock = threading.RLock()
        self.data = fresh(premise_no, seed)
        STATE_DIR.mkdir(exist_ok=True)
        if not keep_log:
            (STATE_DIR / "agent_log.jsonl").write_text("", encoding="utf-8")  # a fresh log for each game
        self.save()

    # -- persistence -------------------------------------------------------
    def save(self):
        """Class 10, slide 2: a ledger not written to disk is lost on restart."""
        with self.lock:
            tmp = STATE_DIR / f"ledger.{os.getpid()}.tmp"
            with open(tmp, "w", encoding="utf-8") as f:
                json.dump(self.data, f, indent=2)
            for attempt in range(10):  # Windows can briefly lock the file (antivirus, an open viewer)
                try:
                    os.replace(tmp, STATE_DIR / "ledger.json")
                    return
                except PermissionError:
                    time.sleep(0.05 * (attempt + 1))
            os.replace(tmp, STATE_DIR / "ledger.json")

    def update(self, fn):
        with self.lock:
            fn(self.data)
            self.save()

    # -- helpers -----------------------------------------------------------
    @property
    def rumor(self) -> dict:
        return self.data["rumors"].get("r1", {})

    def npc(self, key: str) -> dict:
        return self.data["npcs"][key]

    def belief(self, key: str) -> dict | None:
        return self.data["npcs"][key]["beliefs"].get("r1")

    def snapshot(self) -> dict:
        with self.lock:
            return copy.deepcopy(self.data)

    def keywords(self) -> list[str]:
        """Words that tie a line to this game's ledger: names, places and the true event."""
        d = self.data
        out = set()
        for c in cast.CAST.values():
            out.add(c["short"].lower())
        for p in d["town"].get("places", {}).values():
            out.update(w for w in re.findall(r"[a-z']+", p["name"].lower()) if len(w) > 3)
        k = d["truth"].get(d["rumors"].get("r1", {}).get("kernel", ""), {})
        for f in ("what", "how_much", "detail"):
            out.update(w for w in re.findall(r"[a-z0-9']+", str(k.get(f, "")).lower()) if len(w) > 3)
        ev = d.get("evidence", {})
        if ev.get("kind"):
            out.add(ev["kind"].replace("_", " "))
        return sorted(out)


def relevance_score(text: str, keywords: list[str], age: int = 0) -> float:
    """Class 10, slide 4: relevance is set when a branch is born, from recency
    plus keyword match against the ledger."""
    t = text.lower()
    hits = sum(1 for k in keywords if k in t)
    recency = 1.0 / (1 + age)
    return round(0.5 * recency + 0.5 * min(1.0, hits / 4), 3)


def prune_dialogue(history: list[dict], max_turns: int = 6) -> list[dict]:
    """Class 10, slide 4: keep the top branches by relevance_score so the
    prompt never overflows. The latest two turns are always kept."""
    if len(history) <= max_turns:
        return history
    keep_last = history[-2:]
    rest = sorted(history[:-2], key=lambda h: h.get("relevance_score", 0), reverse=True)[: max_turns - 2]
    rest.sort(key=lambda h: h["t"])
    return rest + keep_last
